#!/bin/bash
# fundamentals/02（波形格式与 GTKWave）的判据自动核对
#
# 用法：在沙箱里 bash check.sh
# 核对 VCD 的文本结构（头部两行、信号代号、定义段与时间戳的先后、时间戳计数）
# 与 FST 的二进制性质。源文件与教程第 02 章的实验同一批，在本目录独立重建。
# 各节标题里的"第 N 节"就是正文的小节号。正文"注错见红"由 mutate.sh 实跑。

cd "$(dirname "$0")" || exit 1

PASS=0; FAIL=0; SKIP=0
ok()   { PASS=$((PASS+1)); printf '  PASS  %s\n' "$1"; }
no()   { FAIL=$((FAIL+1)); printf '  FAIL  %s\n' "$1"; [ -n "${2:-}" ] && printf '        %s\n' "$2"; }
skip() { SKIP=$((SKIP+1)); printf '  SKIP  %s\n' "$1"; }

command -v verilator >/dev/null 2>&1 || { echo "找不到 verilator：本脚本要在沙箱里运行"; exit 1; }

B=build
rm -rf "$B" && mkdir -p "$B"
rm -f /tmp/top.vcd /tmp/cnt.vcd /tmp/cnt.fst

echo "=== 环境 ==="
V="$(verilator --version 2>&1 | head -1)"
if grep -qE '^Verilator 5\.052 ' <<< "$V"; then ok 'Verilator 版本是 5.052'; else no 'Verilator 版本是 5.052' "实得 $V"; fi

echo "=== 第 1 节 VCD 的文本结构 ==="
verilator --cc --exe --build -j 0 --top-module top --trace --Mdir "$B/sw" top.v tb_vcd.cpp > "$B/sw.log" 2>&1
"$B/sw/Vtop" > "$B/sw.run" 2>&1
cp /tmp/top.vcd "$B/top.vcd" 2>/dev/null
l1="$(sed -n '1p' "$B/top.vcd" 2>/dev/null)"
l2="$(sed -n '2p' "$B/top.vcd" 2>/dev/null)"
if [ "$l1" = '$version Generated by VerilatedVcd $end' ] && [ "$l2" = '$timescale 1ps $end' ]; then
	ok 'VCD 首两行是 $version 与 $timescale 1ps'
else
	no 'VCD 首两行是 $version 与 $timescale 1ps' "实得第 1 行 [$l1]，第 2 行 [$l2]"
fi
ids="$(grep -m3 '^  \$var wire 1 ' "$B/top.vcd" 2>/dev/null | awk '{print $4 $5}' | tr '\n' ' ')"
if [ "$ids" = '"a #b $f ' ]; then
	ok 'a、b、f 的代号依次是 " # $'
else
	no 'a、b、f 的代号依次是 " # $' "实得 [$ids]"
fi
defl="$(grep -n '^\$enddefinitions' "$B/top.vcd" 2>/dev/null | head -1 | cut -d: -f1)"
tsl="$(grep -n '^#[0-9]' "$B/top.vcd" 2>/dev/null | head -1 | cut -d: -f1)"
if [ -n "$defl" ] && [ -n "$tsl" ] && [ "$defl" -lt "$tsl" ]; then
	ok '定义段结束之后才出现时间戳'
else
	no '定义段结束之后才出现时间戳' "定义段结束行 [$defl]，首个时间戳行 [$tsl]"
fi

echo "=== 第 2 节 一万拍的时间戳计数 ==="
verilator --cc --exe --build -j 0 --top-module cnt --trace --Mdir "$B/cv" cnt.v tb_cnt.cpp > "$B/cv.log" 2>&1
"$B/cv/Vcnt" > "$B/cv.run" 2>&1
cp /tmp/cnt.vcd "$B/cnt.vcd" 2>/dev/null
n="$(grep -c '^#[0-9]' "$B/cnt.vcd" 2>/dev/null)"
if [ "$n" = "10001" ]; then
	ok 'cnt 一万拍的 VCD 有 10001 个时间戳'
else
	no 'cnt 一万拍的 VCD 有 10001 个时间戳' "实得 $n"
fi

echo "=== 第 3 节 FST 是二进制 ==="
verilator --cc --exe --build -j 0 --top-module cnt --trace-fst -CFLAGS -DUSE_FST --Mdir "$B/cf" cnt.v tb_cnt.cpp > "$B/cf.log" 2>&1
"$B/cf/Vcnt" > "$B/cf.run" 2>&1
cp /tmp/cnt.fst "$B/cnt.fst" 2>/dev/null
b1="$(head -c 1 "$B/cnt.fst" 2>/dev/null | od -An -c | tr -d ' ')"
if [ -s "$B/cnt.fst" ] && [ "$b1" != '$' ]; then
	ok 'FST 的首字节不是 $（它不是文本）'
else
	no 'FST 的首字节不是 $（它不是文本）' "首字节 [$b1]"
fi

echo
printf '  %d PASS / %d FAIL / %d SKIP\n' "$PASS" "$FAIL" "$SKIP"
[ "$FAIL" -eq 0 ]
